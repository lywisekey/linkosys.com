export function createLinkosysApp() {
  const app = createApp(App)

  app.component('font-awesome-icon', FontAwesomeIcon)
  app.use(createPinia())
  app.use(router)
  app.use(createBootstrap())
  // BootstrapIconsPlugin registers every icon in the set — 1.03MB of the JS
  // bundle, for the ~152 actually referenced. Registering them explicitly keeps
  // template usage (<BIconSearch />) working at a fraction of the cost.
  Object.entries(bootstrapIcons).forEach(([name, component]) => {
    app.component(name, component)
  })

  return { app, router }
}